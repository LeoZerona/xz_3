import { expect,test } from '@playwright/test'
import { databaseRows,replaceDatabaseRows } from './databaseHelpers'
test('图书管理保存摘录笔记、回到原文，关联删除保留学习数据',async({page})=>{
  test.setTimeout(90000)
  await page.goto('/#/pages/my-books/index')
  await expect(page.getByLabel('搜索图书名称')).toBeVisible({timeout:30000})
  const text='春眠不觉晓。处处闻啼鸟。夜来风雨声。花落知多少。'.repeat(30)
  await replaceDatabaseRows(page,'books',[{id:'library-poem',name:'诗词练习',fileName:'诗词练习.txt',ext:'txt',url:'',source:'custom',createdAt:Date.now(),position:0,textLength:text.length}])
  await replaceDatabaseRows(page,'book_chunks',[{id:'library-poem-0',bookId:'library-poem',position:0,startOffset:0,text}])
  await page.reload()
  await page.getByRole('button').filter({has:page.getByText('诗词练习',{exact:true})}).click()
  await page.getByRole('button',{name:'原文摘录工作台',exact:false}).click()
  await page.getByRole('button',{name:'摘录本段',exact:true}).first().click()
  await page.getByLabel('我的笔记').fill('观察篆书字形与诗句')
  await page.getByLabel('标签（逗号分隔）').fill('古诗，字形')
  await page.getByRole('button',{name:'保存摘录与笔记',exact:true}).click()
  await expect(page.getByText('观察篆书字形与诗句',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByText('观察篆书字形与诗句',{exact:true})).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'回到原文',exact:true}).click()
  await expect(page.locator('.reading-page-stage')).toHaveClass(/is-ready/)
  expect(await databaseRows(page,'annotations')).toHaveLength(1)
  await page.goto('/#/pages/book-detail/index?id=library-poem')
  await page.getByLabel('图书名称').fill('春晓摘录')
  await page.getByRole('button',{name:'保存书名',exact:true}).click()
  await expect(page.getByRole('heading',{name:'春晓摘录',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'删除本书及关联笔记',exact:true}).click()
  await page.getByText('删除图书',{exact:true}).click()
  await expect.poll(()=>databaseRows(page,'annotations')).toHaveLength(0)
  expect(await databaseRows(page,'books')).toHaveLength(0)
})
