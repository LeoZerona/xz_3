import { expect, test } from '@playwright/test'
import { databaseRows, replaceDatabaseRows } from './databaseHelpers'
import { createReviewRecord } from '../src/study/levelReview'
test('跨来源排期去重，旧关卡仍只筛关卡来源，错题可追溯', async ({ page }) => {
  await page.goto('/#/pages/review-center/index')
  await expect(page.getByText('每日课程暂无到期文字。', { exact: false })).toBeVisible({ timeout: 30000 })
  await replaceDatabaseRows(page, 'level_review', ['char-0001', 'char-0002'].map(id => ({ id, ...createReviewRecord('2026-01-01T00:00:00Z') })))
  await replaceDatabaseRows(page, 'settings', [...await databaseRows(page, 'settings'), { id: 'font-learning-review-sources', value: JSON.stringify({ 'char-0001': ['daily'], 'char-0002': ['daily', 'level'] }) }])
  await page.reload()
  await expect(page.getByText('2 字等待复习', { exact: true })).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.daily-review-glyph')).toHaveText('一')
  await page.getByRole('button', { name: '还不认识', exact: true }).click()
  await expect(page.locator('.review-answer-panel')).toContainText('一')
  await expect(page.locator('.review-feedback')).toHaveText('已选择：不认识')
  await expect(page.getByText('1 字等待复习', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '错题本 · 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '下一字', exact: true }).click()
  await expect(page.locator('.daily-review-glyph')).toHaveText('乙')
  await page.getByRole('button', { name: '关卡复习 · 1', exact: true }).click()
  await expect(page.locator('.review-total')).toHaveText('1 字')
  await expect(page.locator('.review-glyph')).toHaveText('乙')
  await page.goto('/#/pages/mistakes/index')
  await expect(page.getByText('错误 1 次 · 待巩固', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /一 认识判断/ }).click()
  await expect(page.getByText('回答错误', { exact: true })).toBeVisible()
  expect((await databaseRows(page, 'level_review')).find(row => row.id === 'char-0001')?.reviewCount).toBe(1)
})

test('每日复习也在作答后展示详情并允许撤回不认识', async ({ page }) => {
  await page.goto('/#/pages/review-center/index')
  await expect(page.getByText('每日课程暂无到期文字。', { exact: false })).toBeVisible()
  await replaceDatabaseRows(page, 'level_review', [{ id: 'char-0001', ...createReviewRecord('2026-01-01T00:00:00Z') }])
  await replaceDatabaseRows(page, 'settings', [...await databaseRows(page, 'settings'), { id: 'font-learning-review-sources', value: JSON.stringify({ 'char-0001': ['daily'] }) }])
  await page.reload()
  await page.getByRole('button', { name: '还不认识', exact: true }).click()
  await expect(page.locator('.review-answer-panel .definition')).toBeVisible()
  await page.getByRole('button', { name: '记错了，改为认识', exact: true }).click()
  await expect(page.locator('.review-feedback')).toHaveText('已选择：认识')
  await expect(page.getByText('0 字等待复习', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '下一字', exact: true })).toBeEnabled()
  await page.screenshot({ path: test.info().outputPath('daily-review-details.png') })
  await page.getByRole('button', { name: '下一字', exact: true }).click()
  await expect(page.getByText('每日课程暂无到期文字。', { exact: false })).toBeVisible()
  expect((await databaseRows(page, 'level_review'))[0]).toMatchObject({ reviewCount: 1, forgottenCount: 0, step: 1 })
  expect((await databaseRows(page, 'activity_events')).filter(row => row.kind === 'answer')).toMatchObject([{ characterId: 'char-0001', correct: 1 }])
})
