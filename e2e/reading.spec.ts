import {expect,test} from '@playwright/test'
test('mobile reading supports catalog, automatic paging, pause and module navigation',async({page})=>{
  await page.goto('/#/pages/reading/index')
  await expect(page.getByRole('navigation',{name:'主导航'})).toBeVisible()
  await page.locator('.book-card').filter({has:page.locator('[data-ext="txt"]')}).first().click()
  await expect(page.locator('.reading-page-stage')).toHaveClass(/is-ready/)
  await expect(page.locator('.learn-char, .cell-learning').first()).not.toContainText('�')
  await page.locator('.reader-file-name').click()
  await page.locator('.bottom-actions-row').getByRole('button',{name:'目录',exact:true}).click()
  await expect(page.locator('.catalog-panel')).toBeVisible()
  await page.locator('.catalog-item').filter({has:page.locator('.type-txt')}).first().click()
  await expect(page.locator('.catalog-panel')).toHaveCount(0)
  await page.locator('.reader-file-name').click()
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.getByRole('button',{name:'表格样式',exact:true}).click()
  await page.locator('.style-card').filter({has:page.locator('[data-mini-style="manuscript-grid"]')}).click()
  await expect(page.locator('.reading-table-wrap')).toHaveAttribute('data-table-style','manuscript-grid')
  await page.getByRole('button',{name:'自动翻页',exact:true}).click()
  await page.clock.install()
  await page.getByRole('button',{name:'开始',exact:true}).click()
  await page.getByRole('button',{name:'关闭设置',exact:true}).click()
  await expect(page.locator('.reading-progress')).toBeVisible()
  const initial=await page.locator('.reading-page-label').textContent()
  await page.clock.fastForward(65_000)
  await expect(page.locator('.reading-page-label')).not.toHaveText(initial!)
  await page.getByRole('button',{name:'暂停自动阅读',exact:true}).click()
  await expect(page.getByRole('button',{name:'继续自动阅读',exact:true})).toBeVisible()
  const current=await page.locator('.reading-page-label').textContent();await page.clock.fastForward(65_000)
  await expect(page.locator('.reading-page-label')).toHaveText(current!)
  await page.getByRole('button',{name:'返回书库',exact:true}).click()
  await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'学习',exact:true}).click()
  await expect(page.getByText('今日计划',{exact:true})).toBeVisible()
})
