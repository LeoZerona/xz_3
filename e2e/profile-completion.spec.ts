test('本机身份与头像保存后可恢复，离线退出保留资料',async({page})=>{
  await page.goto('/#/pages/profile/index')
  await expect(page.getByText(/local-[a-f0-9]{12}/)).toBeVisible()
  const identity=await page.getByText(/local-[a-f0-9]{12}/).textContent()
  await page.getByRole('button',{name:'查看个人资料',exact:true}).click()
  await expect(page.getByText('离线未获取',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'编辑头像',exact:true}).click()
  const chooser=page.waitForEvent('filechooser')
  await page.getByRole('button',{name:'选择头像图片',exact:true}).click()
  await (await chooser).setFiles({name:'avatar.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aN5sAAAAASUVORK5CYII=','base64')})
  await expect(page.getByRole('img',{name:'裁剪后的头像'})).toBeVisible()
  await page.getByRole('button',{name:'保存头像',exact:true}).click()
  await expect(page).toHaveURL(/personal-profile/)
  await expect(page.locator('.profile-avatar')).toHaveCSS('background-image',/data:image\/png/)
  await page.goto('/#/pages/settings/index')
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await expect(page.getByText('当前为离线档案，未登录账号，学习数据已保留',{exact:true})).toBeVisible()
  await page.goto('/#/pages/profile/index');await page.reload()
  await expect(page.getByText(/local-[a-f0-9]{12}/)).toHaveText(identity!)
  await expect(page.locator('.identity .avatar')).toHaveCSS('background-image',/data:image\/png/)
})

test('资料码先预览去重与未知字，拒绝网址，资源显示真实字库',async({page})=>{
  await page.goto('/#/pages/scan-import/index')
  await page.getByLabel('资料码或汉字文本').fill('https://example.com')
  await page.getByRole('button',{name:'解析导入预览',exact:true}).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByLabel('资料码或汉字文本').fill('未末未𠮷')
  await page.getByRole('button',{name:'解析导入预览',exact:true}).click()
  await expect(page.getByText('已收录 2 字',{exact:true})).toBeVisible()
  await expect(page.getByText('未收录：𠮷',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'确认导入字单',exact:true}).click()
  await expect(page).toHaveURL(/collection-detail/)
  expect(await databaseRows(page,'collection_items')).toHaveLength(2)
  await page.goto('/#/pages/resources/index')
  await expect(page.getByText('8105 字 · 815 关',{exact:true})).toBeVisible()
})
