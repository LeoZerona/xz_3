import { expect, test } from '@playwright/test'
import { databaseRows, replaceDatabaseRows } from './databaseHelpers'

test('收藏入口可建立字单、预览批量添加、管理成员并在刷新后保留', async ({ page }) => {
  test.setTimeout(90000)
  await page.goto('/#/pages/profile/index')
  await expect(page.locator('.profile-page')).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.database-overlay')).toHaveCount(0, { timeout: 30000 })
  await page.getByRole('button', { name: '我的收藏', exact: true }).click()
  await expect(page).toHaveURL(/pages\/collections\/index/)
  await page.getByRole('tab', { name: '自定义字单' }).click()
  await page.getByRole('button', { name: '新建字单', exact: true }).click()
  await page.getByLabel('字单名称').fill('横画易混字')
  await page.getByLabel('字单说明').fill('未和末的辨认')
  await page.getByRole('button', { name: '保存字单', exact: true }).click()
  await expect(page.getByRole('heading', { name: '横画易混字' })).toBeVisible()
  await page.getByRole('button', { name: '添加文字', exact: true }).click()
  await page.getByLabel('输入汉字').fill('未末未𠮷')
  await page.getByRole('button', { name: '预览添加', exact: true }).click()
  await expect(page.getByText('未收录：𠮷', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '加入字单', exact: true }).click()
  await expect(page).toHaveURL(/pages\/collection-detail\/index/)
  await expect(page.getByRole('heading', { name: '横画易混字' })).toBeVisible()
  expect(await page.evaluate('getCurrentPages().filter((entry) => entry.route === "pages/collection-detail/index").length')).toBe(1)
  await expect(page.getByRole('button', { name: '查看未的文字详情', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看末的文字详情', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '横画易混字' })).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: '管理文字', exact: true }).click()
  await page.getByRole('checkbox', { name: '选择未', exact: true }).click()
  await page.getByRole('button', { name: '保存成员', exact: true }).click()
  await expect(page.getByRole('button', { name: '查看未的文字详情', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '查看末的文字详情', exact: true })).toBeVisible()
})

test('收藏新页面的手机宽度及深色主题没有横向溢出', async ({ page }) => {
  await page.goto('/#/pages/theme/index')
  await page.getByRole('radio', { name: /墨夜/ }).click()
  for (const width of [320, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/#/pages/collections/index')
    await expect(page.locator('.feature-page')).toBeVisible({ timeout: 30000 })
    await expect(page.locator('.feature-page')).toHaveCSS('background-color', 'rgb(21, 25, 34)')
    const tabTops = await page.getByRole('tab').evaluateAll((tabs) => tabs.map((tab) => Math.round(tab.getBoundingClientRect().top)))
    expect(new Set(tabTops).size).toBe(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
  }
})

test('收藏字支持汉字和带声调拼音搜索，空匹配不会显示全部文字', async ({ page }) => {
  await page.goto('/#/pages/collections/index')
  await expect(page.locator('.database-overlay')).toHaveCount(0, { timeout: 30000 })
  await expect(page.locator('.feature-page')).toBeVisible({ timeout: 30000 })
  await expect(page.getByLabel('搜索收藏文字')).toBeVisible({ timeout: 30000 })
  const characters = (await databaseRows(page, 'characters')).filter((row) => row.simplified === '未' || row.simplified === '末')
  expect(characters).toHaveLength(2)
  await replaceDatabaseRows(page, 'character_progress', characters.map((row) => ({ id: row.id, favorite: 1, excluded: 0, status: 'not-started',
    firstStartedAt: null, lastStudiedAt: null, completedAt: null, favoriteChangedAt: new Date().toISOString(), excludedChangedAt: null })))
  await page.reload()
  await expect(page.getByText('当前范围 2 字', { exact: true })).toBeVisible({ timeout: 30000 })
  await page.getByLabel('搜索收藏文字').fill('未')
  await expect(page.getByRole('button', { name: '查看未的文字详情', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看末的文字详情', exact: true })).toHaveCount(0)
  await page.getByLabel('搜索收藏文字').fill('wèi')
  await expect(page.getByRole('button', { name: '查看未的文字详情', exact: true })).toBeVisible()
  await page.getByLabel('搜索收藏文字').fill('不存在')
  await expect(page.getByText('没有匹配的文字', { exact: true })).toBeVisible()
})
