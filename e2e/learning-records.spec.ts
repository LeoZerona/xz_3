import { expect, test } from '@playwright/test'
import { databaseRows, replaceDatabaseRows } from './databaseHelpers'
test('原菜单进入档案、跨年日历、空日期详情与次日设置', async ({page})=>{
  await page.goto('/#/pages/profile/index')
  await page.getByRole('button',{name:'我的学习',exact:true}).click()
  await expect(page.getByText('累计已学 0 字',{exact:true})).toBeVisible({timeout:30000})
  await page.getByRole('button',{name:'学习日历',exact:false}).click()
  await expect(page.getByText('2026年11月',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'下个月',exact:true}).click()
  await page.getByRole('button',{name:'下个月',exact:true}).click()
  await expect(page.getByText('2027年1月',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'2027-1-1 无学习活动',exact:true}).click()
  await expect(page.getByText('当日会话 · 0',{exact:true})).toBeVisible()
  await page.goto('/#/pages/learning-settings/index')
  await page.getByRole('radio',{name:/二级通用字/}).click()
  await page.getByLabel('每日复习目标').fill('35')
  await page.getByRole('button',{name:'保存学习设置',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'已保存，将于明天零点生效'})).toBeVisible()
  const setting = (await databaseRows(page,'settings')).find(row=>row.id==='font-learning-settings')
  expect(JSON.parse(String(setting?.value))).toMatchObject({course:'level1',pending:{course:'level2',reviewTarget:35}})
})
test('测评首答保存并可恢复，报告不改变正式新学',async({page})=>{
  await page.goto('/#/pages/assessment-setup/index')
  await page.getByRole('button',{name:'开始 30 字抽样测评',exact:true}).click()
  await expect(page.locator('.prompt-card')).toBeVisible()
  const prompt=await page.locator('.prompt-character').innerText()
  await page.getByRole('button',{name:`选择文字${prompt.trim()}`,exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'本题首答正确'})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('status').filter({hasText:'本题首答正确'})).toBeVisible({timeout:30000})
  const row=(await databaseRows(page,'settings')).find(item=>item.id==='font-learning-assessments')
  const sessions=JSON.parse(String(row?.value)) as Record<string,{id:string;questions:unknown[]}>
  const session=Object.values(sessions)[0]!
  expect(session.questions).toHaveLength(30)
  await page.goto(`/#/pages/assessment-result/index?id=${encodeURIComponent(session.id)}`)
  await expect(page.getByText('1 / 1 题首答正确',{exact:true})).toBeVisible()
  expect(await databaseRows(page,'character_progress')).toHaveLength(0)
  expect(await databaseRows(page,'activity_events')).toHaveLength(0)
})
