import {expect,test} from '@playwright/test'
test('粘贴资料导入后全文命中可查看上下文并回原文，重复导入有明确提示',async({page})=>{
  await page.goto('/#/pages/book-import/index')
  await page.getByLabel('资料文件名').fill('诗句检索.txt')
  await page.getByLabel('资料正文').fill('独坐幽篁里，弹琴复长啸。深林人不知，明月来相照。')
  await page.getByRole('button',{name:'导入到本机书库',exact:true}).click()
  await expect(page.getByText('已成功导入到本机',{exact:true})).toBeVisible()
  await page.goto('/#/pages/search/index')
  await page.getByRole('tab',{name:'句子模式',exact:true}).click()
  await page.getByRole('searchbox',{name:'搜索汉字或拼音',exact:true}).fill('幽篁')
  await page.locator('.content-search-hit').filter({hasText:'诗句检索'}).click()
  await expect(page.locator('.context-text mark')).toHaveText('幽篁')
  await page.getByRole('button',{name:'在阅读器中打开这个位置',exact:true}).click()
  await expect(page.locator('.reading-page-stage')).toHaveClass(/is-ready/)
  await page.goto('/#/pages/book-import/index')
  await page.getByLabel('资料文件名').fill('重复.txt')
  await page.getByLabel('资料正文').fill('独坐幽篁里，弹琴复长啸。深林人不知，明月来相照。')
  await page.getByRole('button',{name:'导入到本机书库',exact:true}).click()
  await expect(page.getByRole('alert').filter({hasText:'正文重复'})).toBeVisible()
  await expect(page.getByRole('button',{name:'打开已存在的图书',exact:true})).toBeVisible()
})
test('H5文件导入、词语模式与快速变更检索不会残留旧结果',async({page})=>{
  await page.goto('/#/pages/book-import/index')
  await page.getByRole('tab',{name:'选择 TXT / PDF',exact:true}).click()
  await page.getByLabel('选择本地TXT或PDF').setInputFiles({name:'学习.txt',mimeType:'text/plain',buffer:Buffer.from('学习汉字，温故知新。')})
  await page.getByRole('button',{name:'导入到本机书库',exact:true}).click()
  await expect(page.getByText('已成功导入到本机',{exact:true})).toBeVisible()
  await page.goto('/#/pages/search/index')
  await page.getByRole('tab',{name:'词语模式',exact:true}).click()
  await page.getByRole('searchbox',{name:'搜索汉字或拼音',exact:true}).fill('一')
  await expect(page.locator('.content-search-hit').first()).toBeVisible()
  await page.locator('.content-search-hit').first().click()
  await expect(page.getByText('组词关联文字',{exact:true})).toBeVisible()
  await page.goto('/#/pages/search/index')
  await page.getByRole('tab',{name:'文章模式',exact:true}).click()
  const input=page.getByRole('searchbox',{name:'搜索汉字或拼音',exact:true})
  await input.fill('学习');await input.fill('一个肯定不存在的测试短语')
  await expect(page.locator('.content-search-hit')).toHaveCount(0)
  await expect(page.getByText('找到 0 条结果',{exact:true})).toBeVisible()
})
