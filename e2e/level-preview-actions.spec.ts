import { expect, test } from '@playwright/test'
import { characterRecord, databaseRows } from './databaseHelpers'

const firstStageUrl = '/#/pages/level-study/index?category=level1&stageId=level1-stage-01'

test('关卡预览逐字收藏可取消并持久化，与详情同步且不产生答题进度', async ({ page }) => {
  await page.goto(firstStageUrl)
  await expect(page.locator('.character-row')).toHaveCount(10)
  const firstRow = page.locator('.character-row').first()
  const favorite = firstRow.getByRole('button', { name: '收藏一', exact: true })
  const unfavorite = firstRow.getByRole('button', { name: '取消收藏一', exact: true })
  await expect(favorite).toBeVisible({ timeout: 5000 })
  await expect(firstRow.locator('.van-icon-search')).toHaveCount(0)
  await favorite.click()
  await expect(unfavorite).toHaveAttribute('aria-pressed', 'true')
  await expect(page).toHaveURL(new RegExp(firstStageUrl.replace('?', '\\?') + '$'))
  await expect(firstRow.locator('.character')).toHaveCount(1)
  await expect(firstRow.locator('.slash-button')).toHaveAttribute('aria-pressed', 'false')
  const record = await characterRecord(page, 'char-0001')
  expect(Object.values(record.modes)).toHaveLength(3)
  for (const mode of Object.values(record.modes)) {
    expect(mode).toMatchObject({ attempts: 0, mistakes: 0, completedAt: null, firstAttemptAt: null, lastAttemptAt: null })
  }
  expect(await databaseRows(page, 'stage_training_modes')).toEqual([])
  expect(await databaseRows(page, 'level_review')).toEqual([])
  await page.reload()
  await expect(unfavorite).toHaveAttribute('aria-pressed', 'true')
  await firstRow.getByRole('button', { name: '查看一的文字详情', exact: true }).click()
  await expect(page.getByRole('button', { name: '取消收藏当前文字', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '取消收藏当前文字', exact: true }).click()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  await favorite.focus()
  await favorite.press('Space')
  await expect(unfavorite).toHaveAttribute('aria-pressed', 'true')
  await unfavorite.focus()
  await unfavorite.press('Enter')
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  await page.reload()
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
})

test('关卡预览点击可见字形进入详情，交换遮盖后仍支持键盘打开并保留遮盖操作', async ({ page }) => {
  await page.goto(firstStageUrl)
  await expect(page.locator('.character-row')).toHaveCount(10)
  const firstRow = page.locator('.character-row').first()
  const detail = firstRow.getByRole('button', { name: '查看一的文字详情', exact: true })
  await expect(detail).toHaveClass(/character-cell/, { timeout: 5000 })
  await expect(detail.locator('.character')).toHaveText('一')
  const learningFontName = await page.locator('.font-name').first().innerText()
  const referenceFontName = await page.locator('.font-name').nth(1).innerText()
  await firstRow.getByRole('button', { name: `显示一的${referenceFontName}字形` }).click()
  await expect(firstRow.locator('.character')).toHaveCount(2)
  const referenceFontFamily = await firstRow.locator('.toggle-cell .character').evaluate((element) => getComputedStyle(element).fontFamily)
  await firstRow.getByRole('button', { name: `重新遮盖一的${referenceFontName}字形` }).click()
  await expect(firstRow.locator('.character')).toHaveCount(1)
  await detail.click()
  await expect(page).toHaveURL(/character-detail\/index\?id=char-0001&category=level1&stageId=level1-stage-01/)
  await expect(page.getByText('数词，最小的正整数', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.getByRole('button', { name: '交换遮盖字体' }).click()
  await expect(firstRow.getByRole('button', { name: `显示一的${learningFontName}字形` })).toBeVisible()
  await expect(detail.locator('.character')).toHaveCSS('font-family', referenceFontFamily)
  await detail.focus()
  await detail.press('Enter')
  await expect(page).toHaveURL(/character-detail\/index\?id=char-0001&category=level1&stageId=level1-stage-01/)
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page.getByRole('region', { name: '关卡预览' })).toBeVisible()
  expect(await databaseRows(page, 'character_mode_progress')).toEqual([])
})
