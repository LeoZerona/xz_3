import { expect, test } from '@playwright/test'
import { databaseRows } from './databaseHelpers'

test('专项练习中断恢复并记录真实错题，不改变正式学习进度', async ({ page }) => {
  test.setTimeout(90000)
  await page.goto('/#/pages/practice-setup/index?source=custom')
  await expect(page.getByLabel('练习汉字')).toBeVisible({ timeout: 30000 })
  await page.getByLabel('练习汉字').fill('未末')
  await page.getByLabel('本次练习字数').fill('2')
  await page.getByRole('checkbox', { name: /查看对照字体选择学习字体/ }).click()
  await page.getByRole('checkbox', { name: /查看学习字体输入对照字体/ }).click()
  await page.getByRole('button', { name: '开始独立练习', exact: true }).click()
  await expect(page.locator('.prompt-card')).toBeVisible()
  const sessionUrl = page.url()
  const options = page.locator('.character-option')
  const wrong = await options.evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')).find(label => label !== '选择文字未'))
  await page.getByRole('button', { name: wrong!, exact: true }).click()
  await expect(page.getByText('选择错误，请重新选择')).toBeVisible()
  await page.reload()
  await expect(page.getByText('选择错误，请重新选择')).toBeVisible({ timeout: 30000 })
  expect(page.url()).toBe(sessionUrl)
  await page.getByRole('button', { name: '选择文字未', exact: true }).dblclick()
  await page.getByRole('button', { name: '进入下一题', exact: true }).click()
  await page.getByRole('button', { name: '选择文字末', exact: true }).click()
  await page.getByRole('button', { name: '查看练习结果', exact: true }).click()
  await expect(page).toHaveURL(/practice-result/)
  await expect(page.getByText('50%', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看未的文字详情', exact: true })).toBeVisible()
  expect(await databaseRows(page, 'character_progress')).toHaveLength(0)
  expect(await databaseRows(page, 'level_review')).toHaveLength(0)
  const events = await databaseRows(page, 'activity_events')
  expect(events.filter((event) => event.kind === 'answer')).toHaveLength(3)
  await page.getByRole('button', { name: '把易错字保存为字单', exact: true }).click()
  await expect(page.getByRole('heading', { name: '专项练习易错字' })).toBeVisible()
})
