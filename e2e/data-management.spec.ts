import {expect,test} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {databaseRows} from './databaseHelpers'
test('原入口可导出预览恢复，清索引后保留用户数据',async({page})=>{
  await page.goto('/#/pages/profile/index');await page.getByRole('button',{name:'数据与隐私',exact:true}).click()
  const download=page.waitForEvent('download');await page.getByRole('button',{name:/导出完整备份/}).click()
  const file=await download;const text=await readFile((await file.path())!,'utf8')
  await expect(page.getByRole('heading',{name:'备份文件已导出'})).toBeVisible()
  await page.goto('/#/pages/backup-preview/index')
  await page.getByLabel('备份 JSON 内容').fill(text)
  await page.getByRole('button',{name:'校验并预览备份',exact:true}).click()
  await expect(page.getByRole('heading',{name:'备份校验通过'})).toBeVisible()
  await page.getByRole('button',{name:'确认替换恢复',exact:true}).click()
  await page.getByText('确认替换',{exact:true}).click()
  await expect(page.getByRole('heading',{name:'本机数据已恢复'})).toBeVisible()
  const before=await databaseRows(page,'settings')
  await page.goto('/#/pages/cache-management/index')
  await page.getByRole('button',{name:'清理全文索引缓存',exact:true}).click();await page.getByText('清理索引',{exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'全文索引已清理'})).toBeVisible()
  expect(await databaseRows(page,'settings')).toEqual(before)
})
test('帮助可检索阅读，本地反馈保存导出与删除',async({page})=>{
  await page.goto('/#/pages/help/index');await page.getByLabel('搜索帮助').fill('PDF')
  await page.getByRole('button',{name:/TXT、PDF 导入与重复内容/}).click()
  await expect(page.getByText(/扫描版、加密或没有文字层/)).toBeVisible()
  await page.goto('/#/pages/feedback/index');await page.getByLabel('问题或建议').fill('某书导入失败，请改进错误提示')
  await page.getByRole('button',{name:'保存到本机草稿',exact:true}).click()
  await expect(page.getByRole('heading',{name:'问题 · 本地草稿'})).toBeVisible()
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'导出此反馈',exact:true}).click()
  const text=await readFile((await(await download).path())!,'utf8');expect(JSON.parse(text)).toMatchObject({body:'某书导入失败，请改进错误提示',diagnostics:null})
  await expect(page.getByRole('status')).toContainText('文件已导出')
  await page.getByRole('button',{name:'删除本地草稿',exact:true}).click();await page.getByText('删除草稿',{exact:true}).click()
  await expect(page.getByText('已保存草稿 · 0',{exact:true})).toBeVisible()
})
