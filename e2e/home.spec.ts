test('可切换多套主题并在刷新后保留选择', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', (error) => pageErrors.push(error.message))
  await page.goto('/')
  await page.getByLabel('我').click()
  await expect(page.getByText('主题配色', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '主题配色' }).click()
  await expect(page.getByRole('radio')).toHaveCount(5)

  const blueTheme = page.getByRole('radio', { name: /晴空蓝/ })
  const greenTheme = page.getByRole('radio', { name: /青竹绿/ })
  await greenTheme.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'jade-green')
  await expect(page.locator('html')).toHaveCSS('--color-primary', '#16856b')
  await expect(greenTheme).toHaveAttribute('aria-checked', 'true')
  await expect(greenTheme.locator('.choice-dot-fill')).toHaveCSS('opacity', '1')
  await expect(blueTheme).toHaveAttribute('aria-checked', 'false')
  await expect(blueTheme.locator('.choice-dot-fill')).toHaveCSS('opacity', '0')

  await page.getByRole('radio', { name: /墨夜/ }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'ink-night')
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'dark')

  await page.getByRole('radio', { name: /新春红/ }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'spring-festival')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'spring-festival')
  await expect(page.getByRole('radio', { name: /新春红/ })).toHaveAttribute('aria-checked', 'true')
  await page.screenshot({ path: 'artifacts/theme-mobile.png', fullPage: true })
  expect(pageErrors).toEqual([])
})

