  await expect(page.locator('.action-button').first()).toHaveCSS('height', '58px')
  await expect(page.locator('.bottom-navigation')).toHaveCSS('min-height', '72px')
  await expect(page.getByRole('button', { name: '搜索' })).toBeVisible()
  await expect(page.getByRole('button', { name: '消息提示' })).toBeVisible()
  await expect(page.getByRole('button', { name: '主题设置' })).toHaveCount(0)
  await expect(page.getByText('字体一')).toBeVisible()
  await expect(page.getByText('字体二')).toBeVisible()
  await expect(page.getByText('今日计划')).toBeVisible()
  await expect(page.getByRole('button', { name: '修改' })).toBeVisible()
  await expect(page.getByText('已新学')).toBeVisible()
  await expect(page.getByText('已复习')).toBeVisible()
  await expect(page.getByText('已学习时长')).toBeVisible()
  await expect(page.getByText('x/y')).toHaveCount(2)
  await expect(page.getByText('xxx min')).toBeVisible()
  await expect(page.getByRole('button', { name: '学习', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '复习', exact: true })).toBeVisible()
  await expect(page.getByText('功能切换')).toHaveCount(0)
  const navigationItems = page.locator('.navigation-item')
  await expect(navigationItems).toHaveCount(4)
  const hasStackedNavigationContent = await page.locator('.navigation-content').evaluateAll((items) => (
    items.every((item) => {
      const icon = item.querySelector('.van-icon')
      const label = item.querySelector('.navigation-label')
      if (!icon || !label) return false
      return icon.getBoundingClientRect().bottom <= label.getBoundingClientRect().top
    })
  ))
  expect(hasStackedNavigationContent).toBe(true)
  await expect(page.getByText('单字练习')).toBeVisible()
  await expect(page.getByText('对照阅读')).toBeVisible()
  await expect(page.getByText('我', { exact: true })).toBeVisible()
  await expect(page.getByText('今天要做的事')).toHaveCount(0)
  await page.screenshot({ path: 'artifacts/home-mobile.png', fullPage: true })

  await page.getByRole('button', { name: '修改' }).click()
  await expect(page.getByText('修改计划', { exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: '修改字体' })).toBeVisible()
  await expect(page.getByText('学习字体：字体一')).toBeVisible()
  await expect(page.getByText('选择学习模式（支持多选）')).toBeVisible()
  await page.getByRole('button', { name: '返回' }).click()
  await expect(page.getByText('今日计划')).toBeVisible()
  await page.getByRole('button', { name: '修改' }).click()
  await expect(page.getByText('修改计划', { exact: true })).toBeVisible()
  await expect(page.locator('.plan-wheel')).toBeVisible()
  await expect(page.locator('.picker-row').first()).toHaveCSS('height', '54px')
  await expect(page.locator('.save-button').first()).toHaveCSS('height', '52px')
  await expect(page.locator('uni-picker-view')).toHaveCount(0)
  await expect(page.locator('uni-radio')).toHaveCount(0)
  const wheel = page.locator('.plan-wheel')
  await expect(wheel).toHaveAttribute('data-selected-count', '15')
  await wheel.hover()
  await page.mouse.wheel(0, 80)
  await expect(wheel).toHaveAttribute('data-selected-count', '20')
  await page.mouse.wheel(0, 10000)
  await expect(wheel).toHaveAttribute('data-selected-count', '100')
  await page.waitForTimeout(300)
  const firstMode = page.locator('.mode-card').filter({ hasText: '查看学习字体选择对照字体' })
  const secondMode = page.locator('.mode-card').filter({ hasText: '查看对照字体选择学习字体' })
  await firstMode.click()
  await secondMode.click()
  await expect(firstMode.locator('.uni-checkbox-input svg')).toHaveCount(1)
  await expect(secondMode.locator('.uni-checkbox-input svg')).toHaveCount(1)
